"""Generate a hash-pinned pip lock for a NoorVox engine pack (see docs/adr/0002-qwen3-tts-and-gpu.md).

  python -I tools/gen_engine_lock.py <pins.txt> <out.lock>

<pins.txt> holds exact `name==version` lines (the tested set, e.g. `pip freeze` of a working runtime).
Every line of the output carries the sha256 of every published file for that exact version, taken from
PyPI's JSON API or, for `+cuXXX` local versions, from the PyTorch index. NoorVox installs it with
`pip install --require-hashes --no-deps`, so nothing unpinned or unverified can be installed.
"""
import json
import re
import sys
import urllib.request

UA = {"User-Agent": "noorvox-gen-engine-lock"}
TORCH_INDEX = "https://download.pytorch.org/whl/{variant}/{name}/"


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read().decode("utf-8")


def pypi_hashes(name, version):
    data = json.loads(get(f"https://pypi.org/pypi/{name}/{version}/json"))
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def torch_hashes(name, version):
    variant = version.split("+", 1)[1]
    page = get(TORCH_INDEX.format(variant=variant, name=name.lower()))
    wanted = version.replace("+", "%2B")
    hashes = set()
    for href in re.findall(r'href="([^"]+)"', page):
        file = href.rsplit("/", 1)[-1]
        if f"-{wanted}-" in file and "#sha256=" in file:
            hashes.add(file.split("#sha256=", 1)[1])
    return sorted(hashes)


def main():
    pins_path, out_path = sys.argv[1], sys.argv[2]
    lines = ["# Generated by tools/gen_engine_lock.py. Do not edit by hand."]
    for raw in open(pins_path, encoding="utf-8"):
        pin = raw.split("#", 1)[0].strip()
        if not pin:
            continue
        name, version = pin.split("==")
        hashes = torch_hashes(name, version) if "+" in version else pypi_hashes(name, version)
        if not hashes:
            sys.exit(f"no published files found for {pin}")
        lines.append(f"{name}=={version} " + " ".join(f"--hash=sha256:{h}" for h in hashes))
        print(f"{pin}: {len(hashes)} file(s)", file=sys.stderr)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
